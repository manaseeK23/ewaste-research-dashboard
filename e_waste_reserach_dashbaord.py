    ax.set_title(
        "XGBoost vs Random Forest Performance",
        fontsize=14
    )

    ax.set_ylim(
        0,
        max(1.1, max(r2_values) + 0.1)
    )

    for bar, value in zip(bars, r2_values):

        ax.text(
            bar.get_x() + bar.get_width() / 2,
            value,
            f"{value:.3f}",
            ha="center",
            va="bottom"
        )

    plt.tight_layout()

    return fig


