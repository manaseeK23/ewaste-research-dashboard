def get_city_data(city):

    if not city:
        return [None] * 6

    city_data = df[df["City"] == city].copy()

    if city_data.empty:
        return [None] * 6

    if "Year" in city_data.columns:
        latest_row = city_data.sort_values("Year").iloc[-1]
    else:
        latest_row = city_data.iloc[-1]

    return [
        float(latest_row["Population_Density"]),
        float(latest_row["Urbanization_Rate"]),
        float(latest_row["Per_Capita_Income"]),
        float(latest_row["Digital_Adoption_Rate"]),
        float(latest_row["Awareness_Count"]),
        float(latest_row["Recycling_Rate"])
    ]


